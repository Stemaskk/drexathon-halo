"""Condense and redact an Intern `--json` event log for publication.

Drops token-level reasoning deltas, redacts API-key-like strings and absolute local paths,
and writes <name>.events.jsonl plus a Markdown transcript summary.

Usage: python scripts/sanitize_intern_log.py docs/intern/run1.raw.jsonl
"""
import json
import re
import sys
from pathlib import Path

KEY_RE = re.compile(r"(nace_sk_[A-Za-z0-9_\-]+|sk-di-[A-Za-z0-9]+|keen_[A-Za-z0-9_\-]+|sk-[A-Za-z0-9]{20,})")
ROOT = str(Path(__file__).resolve().parents[1])
HOME = str(Path.home())


def scrub(s: str) -> str:
    s = KEY_RE.sub("[REDACTED_KEY]", s)
    s = s.replace(ROOT, "<repo>").replace(ROOT.replace(" ", "\\ "), "<repo>").replace(HOME, "~")
    return s


def main(path: str) -> None:
    src = Path(path)
    events = [json.loads(l) for l in src.read_text().splitlines() if l.strip()]
    kept = [e for e in events if e.get("type") not in ("reasoning_delta", "text_delta")]
    stem = src.name.replace(".raw.jsonl", "")
    out = src.with_name(f"{stem}.events.jsonl")
    out.write_text("\n".join(scrub(json.dumps(e, ensure_ascii=False)) for e in kept) + "\n")

    lines = [f"# Intern run `{stem}` — sanitized transcript", "",
             "Generated by `scripts/sanitize_intern_log.py` from Intern's `--json` event stream. "
             "Token-level reasoning deltas are omitted; keys and local paths are redacted.", ""]
    decisions = [e for e in events if e.get("type") == "decision"]
    for e in events:
        t = e.get("type")
        if t == "run_start":
            lines.append(f"- **run_start** {scrub(json.dumps({k: v for k, v in e.items() if k in ('system1', 'system2', 'model', 'decider')}))}")
        elif t == "turn_start":
            lines.append(f"\n## Turn {e.get('turn')}")
        elif t == "message" and e.get("message", {}).get("role") == "assistant":
            m = e["message"]
            if m.get("text"):
                lines.append(f"**Assistant:** {scrub(m['text'])[:1500]}")
        elif t == "tool_call_start":
            args = scrub(json.dumps(e.get("arguments"), ensure_ascii=False))
            lines.append(f"- tool `{e.get('name')}`: `{args[:400]}`")
        elif t == "tool_call_end":
            content = scrub(str(e.get("content", "")))
            lines.append(f"  - → {e.get('status')}: ```{content[:600]}```")
    lines += ["", "## Drex supervision decisions inside Intern",
              f"{len(decisions)} decision calls; purposes: " + ", ".join(sorted({d.get('purpose', '?') for d in decisions})),
              f"Total decision input tokens: {sum(d.get('input_tokens', 0) for d in decisions)}"]
    src.with_name(f"{stem}.transcript.md").write_text("\n".join(lines) + "\n")
    print(f"wrote {out} ({len(kept)} events) and transcript")


if __name__ == "__main__":
    main(sys.argv[1])
